/**
 * The photographs shown for a site: its own, or just its cover.
 *
 * This used to pad a missing gallery with `heroEphesus` and the regional
 * artwork so the strip always held four thumbnails — which meant Heraclea
 * Pontica, on the Black Sea, displayed the Library of Celsus among its own
 * pictures, with nothing on screen to say otherwise. A gallery of one is
 * honest; a gallery padded with another city is not.
 */
export function galleryImages(site: Site) {
  const owned = siteGallery[site.slug];
  if (owned && owned.length > 0) return owned;
  return [coverImage(site)];
}
