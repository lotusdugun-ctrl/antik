/**
 * Writes src/lib/history-index.ts: just the ids, names and data values of the
 * civilizations and people, so a city page can link to them without shipping
 * every biography. Run after editing civilizations.ts or people.ts:
 *   bun scripts/build-history-index.ts
 * A test fails if the index has fallen out of step.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { civilizations } from "@/lib/civilizations";
import { people } from "@/lib/people";

const slim = <T extends { id: string; name: unknown; matches: string[] }>(list: T[]) =>
  list.map(({ id, name, matches }) => ({ id, name, matches }));

const body = `// Generated by scripts/build-history-index.ts — do not edit by hand.
import type { Localized } from "@/lib/i18n";

export type IndexEntry = { id: string; name: Localized; matches: string[] };

export const civilizationIndex: IndexEntry[] = ${JSON.stringify(slim(civilizations), null, 2)};

export const peopleIndex: IndexEntry[] = ${JSON.stringify(slim(people), null, 2)};

export function civilizationFor(value: string) {
  return civilizationIndex.find((entry) => entry.matches.includes(value));
}

export function personFor(value: string) {
  return peopleIndex.find((entry) => entry.matches.includes(value));
}
`;
writeFileSync(join(import.meta.dir, "..", "src", "lib", "history-index.ts"), body);
console.log("history-index.ts written");
