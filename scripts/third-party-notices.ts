/**
 * Write public/third-party-notices.txt: the name, version, licence and licence
 * text of every package the app depends on in production (dependencies of
 * package.json, followed transitively through node_modules). MIT, BSD, ISC and
 * Apache all ask that their notice travel with the code; the credits page
 * links this file.
 *
 *   bun scripts/third-party-notices.ts
 *
 * Re-run after adding or upgrading a dependency (a test checks the file names
 * every direct dependency).
 */
import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = join(import.meta.dir, "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as {
  dependencies: Record<string, string>;
};

type Entry = { name: string; version: string; license: string; text: string };
const seen = new Map<string, Entry>();

function find(name: string, from: string): string | null {
  let dir = from;
  for (;;) {
    const candidate = join(dir, "node_modules", name, "package.json");
    if (existsSync(candidate)) return candidate;
    const up = dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}

function licenceText(dir: string): string {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(f));
  return file ? readFileSync(join(dir, file), "utf8").trim() : "";
}

function walk(name: string, from: string) {
  const path = find(name, from);
  if (!path) return;
  const real = realpathSync(path);
  if (seen.has(real)) return;
  const json = JSON.parse(readFileSync(path, "utf8")) as {
    name: string;
    version: string;
    license?: string | { type: string };
    licenses?: { type: string }[];
    dependencies?: Record<string, string>;
    optionalDependencies?: Record<string, string>;
  };
  const license =
    typeof json.license === "string"
      ? json.license
      : (json.license?.type ?? json.licenses?.map((l) => l.type).join(" OR ") ?? "UNKNOWN");
  seen.set(real, {
    name: json.name,
    version: json.version,
    license,
    text: licenceText(dirname(path)),
  });
  for (const dep of Object.keys({ ...json.dependencies, ...json.optionalDependencies }))
    walk(dep, dirname(path));
}

for (const dep of Object.keys(pkg.dependencies)) walk(dep, root);

const entries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const copyleft = entries.filter((e) => /\b(A?GPL|LGPL|SSPL|EUPL)\b/i.test(e.license));
if (copyleft.length) {
  console.error(
    "Copyleft licences found:",
    copyleft.map((e) => `${e.name} ${e.license}`),
  );
  process.exit(1);
}
const out = [
  "Antik Türkiye — third-party software notices",
  "=============================================",
  "",
  `${entries.length} packages. Generated by scripts/third-party-notices.ts.`,
  "",
  ...entries.flatMap((e) => [
    "-".repeat(78),
    `${e.name}@${e.version} — ${e.license}`,
    "",
    e.text || "(no licence file in the package; licence as declared above)",
    "",
  ]),
].join("\n");
writeFileSync(join(root, "public", "third-party-notices.txt"), out + "\n");
console.log(`${entries.length} packages written to public/third-party-notices.txt`);
